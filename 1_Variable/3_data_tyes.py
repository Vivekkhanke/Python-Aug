# Integer data type
age = 22
marks = 98
temperature = -5
print(type(temperature))

# Float data type
pi = 3.14
salary = 50000.50
height = 5.8
print(type(pi))
print(type(salary))
print(type(height))

# String Data Type
name = "Vivek"
city = 'Pune'
print(type(name))
print(type(city))

# Boolean Data Type
is_logged_in = True
is_admin = False

is_password_correct = True
is_payment_done = False

print(type(is_logged_in))
print(type(is_admin))
print(type(is_password_correct))
print(type(is_payment_done))